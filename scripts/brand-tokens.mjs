import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(readFileSync(new URL("../brand/tokens.json", import.meta.url), "utf8"));
const themeTokens = [...tokens.color.tokens, ...tokens.shadow.tokens];
const variables = (items, theme) => items.map(({ name, value }) =>
  `  --${name}: ${typeof value === "string" ? value : value[theme]};`).join("\n");
const staticTokens = [
  ...tokens.spacing.tokens, ...tokens.radius.tokens, ...tokens.size.tokens,
  ...Object.entries(tokens.type.families).map(([name, value]) => ({ name: `font-${name}`, value })),
];
const fonts = tokens.type.fonts.map(({ family, file, weight, style }) =>
  `@font-face { font-family: "${family}"; src: url("/brand/${file}") format("woff2"); font-weight: ${weight}; font-style: ${style}; font-display: swap; }`);
const dark = variables(themeTokens, "dark");
writeFileSync(new URL("../brand/tokens.css", import.meta.url), [
  "/* Generated by npm run brand:tokens. */", ...fonts,
  `:root {\n${variables([...themeTokens, ...staticTokens], "light")}\n}`,
  `:root[data-theme="dark"] {\n${dark}\n  color-scheme: dark;\n}`,
  `@media (prefers-color-scheme: dark) {\n:root:not([data-theme="light"]) {\n${dark}\n  color-scheme: dark;\n}\n}`,
].join("\n\n") + "\n");
